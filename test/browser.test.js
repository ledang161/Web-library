const { test } = require('node:test');
const assert = require('node:assert/strict');
const { chromium, expect } = require('@playwright/test');
const mysql = require('mysql2/promise');
const { randomBytes, scryptSync } = require('node:crypto');
const fs = require('node:fs/promises');
const { migrate, config } = require('../scripts/migrate');

test('Chromium: student, all admin actions, equipment and mobile with real MySQL', { timeout: 180000 }, async () => {
  const name = `uniborrow_test_browser_${Date.now()}_${randomBytes(3).toString('hex')}`;
  const control = await mysql.createConnection(config(null));
  let pool, server, browser, appPool;
  try {
    await control.query('CREATE DATABASE ??', [name]);
    process.env.DB_NAME = name;
    process.env.APP_ORIGIN = '';
    process.env.NODE_ENV = 'test';
    pool = mysql.createPool(config(name));
    await migrate(pool);
    const salt = randomBytes(16).toString('hex');
    const password = 'Browser-Test-2026!';
    await pool.query('INSERT INTO users(name,email,password,role) VALUES (?,?,?,?)', ['Test Admin','admin@example.test',`scrypt$${salt}$${scryptSync(password,salt,64).toString('hex')}`,'admin']);
    await pool.query("INSERT INTO equipment(name,category,quantity,description,status) VALUES ('Laptop browser','Máy tính',5,'Mô tả thử nghiệm','available'),('Máy hỏng','Khác',0,'','unavailable'),('Camera phụ','Khác',2,'Chi tiết thứ hai','available')");
    const loaded = require('../app'); appPool = loaded.db;
    server = await new Promise(resolve => { const s = loaded.app.listen(0,'127.0.0.1',()=>resolve(s)); });
    const base = `http://127.0.0.1:${server.address().port}`;
    browser = await chromium.launch();
    const studentContext = await browser.newContext();
    const student = await studentContext.newPage();
    const errors = []; student.on('pageerror', e => errors.push(e.message));
    await student.goto(base);
    await expect(student.locator('#authSubmit')).toBeEnabled();
    await student.locator('#authSwitch').click();
    await student.locator('#authName').fill('Test Student');
    await student.locator('#authEmail').fill('student@example.test');
    await student.locator('#authPassword').fill(password);
    await student.locator('#authSubmit').click();
    await expect(student.locator('#currentUser')).toContainText('Test Student');
    await expect(student.locator('#tai-khoan')).toBeHidden();
    await student.locator('#searchEquipment').fill('không tồn tại');
    await student.locator('#equipmentFilters button').click();
    await expect(student.locator('#danhSachThietBi')).toContainText('Không có thiết bị');
    await student.locator('#searchEquipment').fill('Laptop');
    await student.locator('#equipmentFilters button').click();
    await student.getByRole('button',{name:'Xem chi tiết',exact:true}).click();
    await expect(student.locator('#detailContent')).toContainText('Mô tả thử nghiệm');
    await student.locator('#closeDetail').click();
    const today = (await (await studentContext.request.get(base+'/api/auth/me')).json()).today;
    async function submitBorrow() {
      await student.locator('#danhSachThietBi [data-equipment-id="1"]').getByRole('button',{name:'Mượn thiết bị',exact:true}).click();
      await student.locator('#ngayMuon').fill(today);
      await student.locator('#ngayTra').fill(today);
      await student.getByRole('button',{name:'Gửi yêu cầu mượn',exact:true}).click();
      await expect(student.locator('#message')).toContainText('Gửi yêu cầu thành công');
      await expect(student.locator('#form-muon')).toBeHidden();
      const rows = await (await studentContext.request.get(base+'/api/my/borrow-requests')).json();
      return rows[0].id;
    }
    const id = await submitBorrow();
    await pool.query('INSERT INTO borrow_details(request_id,equipment_id,quantity) VALUES (?,3,1)',[id]);
    await student.locator('#refreshHistory').click();
    await expect(student.locator(`[data-request-id="${id}"] li`)).toHaveCount(2);
    const adminContext = await browser.newContext();
    const admin = await adminContext.newPage(); admin.on('pageerror',e=>errors.push(e.message));
    await admin.goto(base);
    await admin.locator('#authEmail').fill('admin@example.test');
    await admin.locator('#authPassword').fill(password);
    await admin.locator('#authSubmit').click();
    await expect(admin.locator('#adminLink')).toBeVisible();
    await admin.locator('#adminLink').click();
    await expect(admin.locator(`[data-request-id="${id}"] li`)).toHaveCount(2);
    async function action(requestId,label,state) {
      const card=admin.locator(`[data-request-id="${requestId}"]`);
      await card.getByRole('button',{name:label,exact:true}).click();
      await expect(admin.locator('#confirmDialog')).toBeVisible();
      await admin.locator('#confirmYes').click();
      await expect(card.locator('.status-badge')).toHaveText(state);
    }
    await action(id,'Duyệt','Đã duyệt');
    await action(id,'Bàn giao','Đang mượn');
    await action(id,'Xác nhận trả','Đã trả');
    const rejectId = await submitBorrow();
    await admin.locator('#refreshRequests').click();
    await action(rejectId,'Từ chối','Từ chối');
    const cancelId=await submitBorrow();
    const cancelCard=student.locator(`[data-request-id="${cancelId}"]`);
    await cancelCard.getByRole('button',{name:'Hủy yêu cầu',exact:true}).click();
    await student.locator('#confirmYes').click();
    await expect(cancelCard.locator('.status-badge')).toHaveText('Đã hủy');
    await admin.locator('#newEquipment').click();
    await admin.locator('#editName').fill('Thiết bị mới');
    await admin.locator('#editCategory').fill('Thử nghiệm');
    await admin.locator('#editQuantity').fill('2');
    await admin.getByRole('button',{name:'Lưu thiết bị',exact:true}).click();
    await expect(admin.locator('#equipmentEditor')).toBeHidden();
    const newCard=admin.locator('#equipmentList .card').filter({hasText:'Thiết bị mới'});
    await expect(newCard).toBeVisible();
    await newCard.getByRole('button',{name:'Sửa thiết bị',exact:true}).click();
    await admin.locator('#editName').fill('Thiết bị đã sửa');
    await admin.getByRole('button',{name:'Lưu thiết bị',exact:true}).click();
    const edited=admin.locator('#equipmentList .card').filter({hasText:'Thiết bị đã sửa'});
    await expect(edited).toBeVisible();
    await edited.getByRole('button',{name:'Xóa thiết bị',exact:true}).click();
    await admin.locator('#confirmYes').click();
    await expect(edited).toHaveCount(0);
    await admin.locator('#requestStatus').selectOption('returned');
    await admin.getByRole('button',{name:'Lọc yêu cầu',exact:true}).click();
    await expect(admin.locator('#requestList .request-card')).toHaveCount(1);
    await fs.mkdir('test-results',{recursive:true});
    await admin.screenshot({path:'test-results/admin-desktop.png',fullPage:true});
    await student.setViewportSize({width:375,height:812});
    await student.reload();
    await expect(student.locator('#currentUser')).toContainText('Test Student');
    assert.equal(await student.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
    await student.screenshot({path:'test-results/student-mobile.png',fullPage:true});
    await admin.setViewportSize({width:375,height:812});
    assert.equal(await admin.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
    await admin.locator('#requestStatus').selectOption('');
    await admin.getByRole('button',{name:'Lọc yêu cầu',exact:true}).click();
    await admin.locator('#refreshRequests').click();
    const mobileId=await submitBorrow();
    await admin.locator('#refreshRequests').click();
    await action(mobileId,'Duyệt','Đã duyệt');
    await action(mobileId,'Bàn giao','Đang mượn');
    await action(mobileId,'Xác nhận trả','Đã trả');
    const historic=admin.locator('#equipmentList [data-equipment-id="1"]');
    await historic.getByRole('button',{name:'Xóa thiết bị',exact:true}).click();
    await admin.locator('#confirmYes').click();
    await expect(historic).toContainText('Ngừng cho mượn');
    await expect(admin.locator(`[data-request-id="${id}"] li`)).toHaveCount(2);
    await admin.screenshot({path:'test-results/admin-mobile.png',fullPage:true});
    await student.locator('#logout').click();
    await expect(student.locator('#authSubmit')).toBeVisible();
    await student.locator('#authEmail').fill('student@example.test');
    await student.locator('#authPassword').fill('wrong-password');
    await student.locator('#authSubmit').click();
    await expect(student.locator('#message')).toHaveClass(/error/);
    await student.locator('#authPassword').fill(password);
    await student.locator('#authSubmit').click();
    await expect(student.locator('#currentUser')).toContainText('Test Student');
    assert.deepEqual(errors,[]);
  } finally {
    if(browser)await browser.close();
    if(server)await new Promise(resolve=>server.close(resolve));
    if(appPool)await appPool.end();
    if(pool)await pool.end();
    await control.query('DROP DATABASE ??',[name]);
    await control.end();
  }
});

